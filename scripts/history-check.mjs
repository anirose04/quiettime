#!/usr/bin/env node
/* Quiet Time — integrity check for the history paper's discovery collection. Exits 1 on any error.
   Offline by default: every discovery has a period text, resolvable citations and 2–3 valid links.
   With --verify-excerpts it also downloads each source text and checks each excerpt word for word.
   Usage: node scripts/history-check.mjs [--verify-excerpts] */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const Q = f => path.join(ROOT, 'quiet-time', f);
const code = (await Promise.all(['history-issues.js', 'history-discoveries.js'].map(f => readFile(Q(f), 'utf8')))).join('\n');
const ctx = vm.createContext({});
vm.runInContext(code + '\nthis.D = HISTORY_DISCOVERIES; this.S = HISTORY_SOURCES; this.I = HISTORY_ISSUES;', ctx);
const { D, S, I } = ctx;
const errors = [], warnings = [];
const ids = new Map(D.map(d => [d.id, d]));
if (ids.size !== D.length) errors.push('duplicate discovery ids');
const RELS = new Set(['same', 'linked', 'debate', 'idea', 'cousin']);
const words = s => s.replace(/<[^>]+>/g, ' ').trim().split(/\s+/).length;
for (const d of D) {
  const w = m => errors.push(`${d.id}: ${m}`);
  const issue = d.issue && I.find(i => i.id === d.issue);
  if (d.issue && !issue) w(`unknown issue ${d.issue}`);
  const src = k => issue?.sources[k] || S[k];
  if (!['everyday', 'ideas', 'power'].includes(d.cat)) w(`bad category ${d.cat}`);
  if (!['scholarly', 'reference', 'text'].includes(d.context)) w(`bad context ${d.context}`);
  if (!src(d.main)) w(`unknown main source ${d.main}`);
  if (d.head !== d.head.toLowerCase()) w('headline must be lowercase');
  const n = words(d.card);
  if (n < 45 || n > 100) warnings.push(`${d.id}: card is ${n} words`);
  if (!issue) {
    if (!d.excerpt?.text || !d.excerpt.textUrl || !d.excerpt.work || !d.excerpt.by || !d.excerpt.written || !d.excerpt.locator) w('every story needs a complete period text');
    if (d.excerpt && !S[d.excerpt.source]) w(`excerpt cites unknown source ${d.excerpt.source}`);
  } else if (!issue.bookshelf?.excerpt) w('issue has no period text');
  const cites = [...d.story.join(' ').matchAll(/\[\[(\w+)(?:\|[^\]]+)?\]\]/g)].map(m => m[1]);
  if (!cites.length) w('no inline citations');
  for (const c of cites) if (!src(c)) w(`citation to unknown source ${c}`);
  if (d.links.length < 2 || d.links.length > 3) w(`has ${d.links.length} links; want 2–3`);
  if (new Set(d.links.map(l => l[0])).size !== d.links.length) w('duplicate link');
  for (const [to, rel, why] of d.links) {
    if (!ids.get(to)) w(`link to missing discovery ${to}`);
    if (!RELS.has(rel)) w(`bad relation ${rel}`);
    if (!why || why.length < 15) w(`link to ${to} has no real explanation`);
  }
}
const linked = new Set(D.flatMap(d => d.links.map(l => l[0])));
for (const d of D) if (!linked.has(d.id)) warnings.push(`${d.id}: nothing leads here except the feed`);

if (process.argv.includes('--verify-excerpts')) {
  const norm = s => s.normalize('NFKC').replace(/<[^>]+>/g, ' ').replace(/\[\s*\d+\s*\]/g, ' ').replace(/[_*]/g, '')
    .replace(/[‘’`]/g, "'").replace(/[“”]/g, '"').replace(/&quot;/g, '"').replace(/&#160;|&nbsp;/g, ' ').replace(/\s+/g, ' ').trim();
  const cache = new Map();
  const fetchText = async u => {
    if (!cache.has(u)) {
      const res = await fetch(u, { headers: { 'User-Agent': 'quiet-time-history-check/1.0' }, signal: AbortSignal.timeout(60000), redirect: 'follow' });
      if (!res.ok) throw new Error(`${res.status} from ${u}`);
      const t = await res.text();
      cache.set(u, norm(u.includes('wikisource') ? JSON.parse(t).parse.text['*'] : t));
    }
    return cache.get(u);
  };
  let ok = 0;
  for (const d of D.filter(x => x.excerpt)) {
    try {
      const t = await fetchText(d.excerpt.textUrl);
      const miss = d.excerpt.text.split(' … ').filter(p => !t.includes(norm(p)));
      if (miss.length) errors.push(`${d.id}: excerpt not found in source: "${miss[0].slice(0, 70)}…"`); else ok++;
    } catch (e) { errors.push(`${d.id}: could not fetch source (${e.message})`); }
  }
  console.log(`${ok} of ${D.filter(x => x.excerpt).length} excerpts matched word for word`);
}
const collection = D.filter(d => d.excerpt).map(d => d.id);
await writeFile(Q('data/history-collection.json'), JSON.stringify({ _about: 'generated by scripts/history-check.mjs', items: collection }) + '\n');
const stats = Object.fromEntries(['everyday', 'ideas', 'power'].map(c => [c, D.filter(d => d.cat === c).length]));
console.log(`${D.length} discoveries`, stats);
warnings.forEach(w => console.log('warning:', w));
errors.forEach(e => console.error('ERROR:', e));
if (errors.length) { console.error(`${errors.length} error(s)`); process.exit(1); }
console.log('ok');
