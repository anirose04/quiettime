#!/usr/bin/env node
/* Quiet Time — integrity check for the psyc paper's discovery collection. Runs offline; exits 1 on any error.
   Checks that every discovery has a real source, resolvable inline citations and 2–3 valid links, and that
   every link claiming a citation really appears in the OpenAlex reference lists (data/psyc-citation-graph.json).
   Also writes data/psyc-collection.json, which the weekly feed uses to spot new papers citing the collection.
   Usage: node scripts/psyc-check.mjs */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const Q = f => path.join(ROOT, 'quiet-time', f);
const code = (await Promise.all(['psyc-issues.js', 'psyc-discovery-bib.js', 'psyc-discoveries.js'].map(f => readFile(Q(f), 'utf8')))).join('\n');
const ctx = vm.createContext({});
vm.runInContext(code + '\nthis.D = PSYC_DISCOVERIES; this.B = PSYC_BIB; this.I = PSYC_ISSUES;', ctx);
const { D, B, I } = ctx;
const { graph } = JSON.parse(await readFile(Q('data/psyc-citation-graph.json'), 'utf8'));

const errors = [], warnings = [];
const ids = new Map(D.map(d => [d.id, d]));
if (ids.size !== D.length) errors.push('duplicate discovery ids');
const RELS = new Set(['cites', 'citedby', 'failed', 'failedby', 'replicates', 'replicatedby', 'challenges', 'challengedby', 'idea', 'cousin']);
const CITATION = { cites: 1, failed: 1, replicates: 1, challenges: 1, citedby: -1, failedby: -1, replicatedby: -1, challengedby: -1 };
const inGraph = (from, to) => (graph[from] || []).includes(to);
const words = s => s.replace(/<[^>]+>/g, ' ').trim().split(/\s+/).length;

for (const d of D) {
  const w = m => errors.push(`${d.id}: ${m}`);
  if (!['cognitive', 'social', 'educational'].includes(d.cat)) w(`bad category ${d.cat}`);
  if (!['checked', 'abstract'].includes(d.level)) w(`bad level ${d.level}`);
  if (!B[d.bib]) w(`unknown source ${d.bib}`);
  else if (!B[d.bib].apa || !B[d.bib].doi) w(`source ${d.bib} lacks a reference or DOI`);
  if (!d.head || d.head !== d.head.toLowerCase()) w('headline must be lowercase');
  const n = words(d.card);
  if (n < 45 || n > 100) warnings.push(`${d.id}: card is ${n} words`);
  if (!d.story?.length) w('no story text');
  if (d.level === 'abstract' && d.story.some(p => !/abstract|retracted/i.test(p))) w('abstract-level text must say so');
  if (d.digest && !I.some(i => i.id === d.digest)) w(`unknown digest ${d.digest}`);
  const text = [...d.story, ...(d.how || []), ...(d.numbers || [])].join(' ');
  const cites = [...text.matchAll(/\[\[(\w+)(?:\|[^\]]+)?\]\]/g)].map(m => m[1]);
  if (!cites.length) w('no inline citations');
  for (const c of cites) if (!B[c]) w(`citation to unknown source ${c}`);
  if (d.links.length < 2 || d.links.length > 3) w(`has ${d.links.length} links; want 2–3`);
  if (new Set(d.links.map(l => l[0])).size !== d.links.length) w('duplicate link');
  for (const [to, rel, why] of d.links) {
    const t = ids.get(to);
    if (!t) { w(`link to missing discovery ${to}`); continue; }
    if (to === d.id) w('links to itself');
    if (!RELS.has(rel)) w(`bad relation ${rel}`);
    if (!why || why.length < 15) w(`link to ${to} has no real explanation`);
    const dir = CITATION[rel];
    if (rel === 'cites' || rel === 'citedby') {
      const [a, b] = dir === 1 ? [d.bib, t.bib] : [t.bib, d.bib];
      if (!inGraph(a, b)) w(`claims ${a} cites ${b}, but it is not in the OpenAlex reference list`);
    } else if (dir) {
      const [a, b] = dir === 1 ? [d.bib, t.bib] : [t.bib, d.bib];
      if (!inGraph(a, b)) warnings.push(`${d.id} → ${to}: "${rel}" without a citation-graph edge from ${a} to ${b}`);
    }
  }
  if (B[d.bib]?.updates?.some(u => u.type === 'retraction') && !d.retracted) w('source is retracted but not flagged');
  if (d.retracted && !B[d.bib]?.updates?.some(u => u.type === 'retraction')) w('flagged as retracted without a notice');
  for (const u of B[d.bib]?.updates || []) if (!['retraction'].includes(u.type) && !/Crossref update record/.test(text)) warnings.push(`${d.id}: source has a "${u.type}" notice the text does not mention`);
}
const byCat = c => D.filter(d => d.cat === c);
const stats = Object.fromEntries(['cognitive', 'social', 'educational'].map(c => [c, { checked: byCat(c).filter(d => d.level === 'checked').length, abstract: byCat(c).filter(d => d.level === 'abstract').length }]));
const linked = new Set(D.flatMap(d => d.links.map(l => l[0])));
for (const d of D) if (!linked.has(d.id)) warnings.push(`${d.id}: nothing leads to this discovery except the feed`);

const collection = D.map(d => ({ id: d.id, doi: B[d.bib]?.doi, openalex: B[d.bib]?.openalex, cat: d.cat })).filter(x => x.openalex);
await writeFile(Q('data/psyc-collection.json'), JSON.stringify({ _about: 'generated by scripts/psyc-check.mjs; lets the weekly feed notice new papers that cite the collection', items: collection }) + '\n');

console.log(`${D.length} discoveries`, stats);
warnings.forEach(w => console.log('warning:', w));
errors.forEach(e => console.error('ERROR:', e));
if (errors.length) { console.error(`${errors.length} error(s)`); process.exit(1); }
console.log('ok');
